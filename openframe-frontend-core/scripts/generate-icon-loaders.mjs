#!/usr/bin/env node

/**
 * Writes `src/components/icons-v2-generated/icon-loaders.ts`: for every icon in the
 * generated set, a function that loads THAT icon's module and nothing else.
 *
 * The name-to-icon resolver (`chat/utils/icon-library.tsx`) draws an icon it
 * was given by NAME (a stored `icon_name`: a slash command's, a source's, a
 * navigation link's). It used to import the whole set to do that, so every
 * page shipped all ~1,700 icons to draw a few dozen. With this table it loads
 * the icons a page draws.
 *
 * The table is read from each category's `index.ts`, the same list the set's
 * barrel exports, so it cannot name an icon the set does not have. Run by
 * `generate-icons.mjs` after it writes the set, and on its own with
 * `npm run generate:icon-loaders`. `icon-loaders.test.ts` fails when the table
 * and the set disagree.
 *
 * The file is named `icon-loaders`, never `loaders`: `loaders` is one of the
 * set's CATEGORIES (the spinner icons), and a file of that name would shadow it.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const OUTPUT_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src/components/icons-v2-generated');
const EXPORT_LINE = /^export \{ ([\w, ]+) \} from '\.\/([\w-]+)';$/;
/** An icon component's export name. A module may also export a constant beside it (a path's data), which is no icon. */
const ICON_NAME = /^[A-Z][A-Za-z0-9]*Icon$/;

/** Every icon as `{ name, path }`: its export name and its module, relative to the set's root. */
export function listGeneratedIcons() {
  const icons = [];
  const categories = readdirSync(OUTPUT_DIR)
    .filter(item => statSync(join(OUTPUT_DIR, item)).isDirectory())
    .sort();
  for (const category of categories) {
    const lines = readFileSync(join(OUTPUT_DIR, category, 'index.ts'), 'utf8')
      .split('\n')
      .filter(Boolean);
    for (const line of lines) {
      const match = EXPORT_LINE.exec(line.trim());
      if (!match) throw new Error(`generate-icon-loaders: unreadable export in ${category}/index.ts: ${line}`);
      for (const name of match[1].split(',').map(part => part.trim())) {
        if (ICON_NAME.test(name)) icons.push({ name, path: `./${category}/${match[2]}` });
      }
    }
  }
  return icons.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

export function renderIconLoaders(icons) {
  const rows = icons.map(
    ({ name, path }) => `  ${name}: () => import('${path}').then(module => ({ default: module.${name} })),`,
  );
  return `// GENERATED by scripts/generate-icon-loaders.mjs from the categories' index.ts. Do not edit.
import type { ComponentType } from 'react';

/** What every generated icon takes. */
export interface LoadedIconProps {
  size?: number;
  className?: string;
  color?: string;
}

type IconModule = { default: ComponentType<LoadedIconProps> };

/** One loader per icon, keyed by the icon's export name: the module of that icon alone. */
export const ICON_LOADERS: Readonly<Record<string, () => Promise<IconModule>>> = {
${rows.join('\n')}
};
`;
}

export function writeIconLoaders() {
  const icons = listGeneratedIcons();
  writeFileSync(join(OUTPUT_DIR, 'icon-loaders.ts'), renderIconLoaders(icons));
  return icons.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`Wrote loaders for ${writeIconLoaders()} icons.`);
}
